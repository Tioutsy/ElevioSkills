export const CANONICAL_COURSE_IMAGE_MAP = new Map<string, CanonicalCourseImageRecord>(
  CANONICAL_COURSE_IMAGE_MANIFEST.map(c => [c.courseCode, c])
);

export function getCourseImageRecord(courseCodeOrId: string | number): CanonicalCourseImageRecord | undefined {
  if (typeof courseCodeOrId === 'string' && courseCodeOrId.startsWith('ELH-')) {
    return CANONICAL_COURSE_IMAGE_MAP.get(courseCodeOrId);
  }
  const idNum = Number(courseCodeOrId);
  return CANONICAL_COURSE_IMAGE_MANIFEST.find(c => c.dbId === idNum || c.courseCode === courseCodeOrId);
}
